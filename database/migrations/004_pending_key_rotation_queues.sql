-- PR #13: persistent pending E2EE key deliveries and deferred rotation triggers.
-- Apply once to an EXISTING DB already migrated through 003.
-- Back up the database before applying. Fresh DBs use database/schema.sql.
-- Backend should be stopped while upgrading; schema and migration have equivalent DDL.
BEGIN;

-- Pending E2EE key distribution / rotation requests (PR #13).
-- Only ciphertext is queued here, never unencrypted symmetric/private keys.
CREATE TABLE channel_key_pending
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    channel_id bigint NOT NULL,
    recipient_user_id bigint NOT NULL,
    channel_key_id bigint NOT NULL,
    ciphertext bytea NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "PK_channel_key_pending" PRIMARY KEY (id),
    CONSTRAINT "FK_channel_key_pending_channel"
        FOREIGN KEY (channel_id) REFERENCES message_channel (id) ON DELETE CASCADE,
    CONSTRAINT "FK_channel_key_pending_recipient_member"
        FOREIGN KEY (channel_id, recipient_user_id)
        REFERENCES message_channel_member (channel_id, user_id) ON DELETE CASCADE,
    CONSTRAINT "FK_channel_key_pending_key_channel"
        FOREIGN KEY (channel_key_id, channel_id)
        REFERENCES message_channel_key (id, channel_id) ON DELETE CASCADE
);

-- Supports ChannelKeyPendingRepository.findByRecipientUserId(userId).
CREATE INDEX "IX_channel_key_pending_recipient"
    ON channel_key_pending (recipient_user_id, id);
-- Supports cascading removal when a membership is deleted.
CREATE INDEX "IX_channel_key_pending_channel_recipient"
    ON channel_key_pending (channel_id, recipient_user_id);
-- Supports cascading removal when a key generation is deleted.
CREATE INDEX "IX_channel_key_pending_key_channel"
    ON channel_key_pending (channel_key_id, channel_id);

-- One pending key rotation per channel (unique=true on ChannelRotationPending.channelId).
CREATE TABLE channel_rotation_pending
(
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    channel_id bigint NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "PK_channel_rotation_pending" PRIMARY KEY (id),
    CONSTRAINT "UQ_channel_rotation_pending_channel" UNIQUE (channel_id),
    CONSTRAINT "FK_channel_rotation_pending_channel"
        FOREIGN KEY (channel_id) REFERENCES message_channel (id) ON DELETE CASCADE
);

COMMIT;
